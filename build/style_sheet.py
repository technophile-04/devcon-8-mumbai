def swatches():
    out = []
    for name, node in T.tokens("color"):
        out.append(f'<div class="swatch"><div class="chip" style="background: var(--color-{name})"></div>'
                   f'<p class="body medium">{name}</p><p class="tag">{T.hex(name)}</p><p class="label use">{escape(node.get("$description", ""))}</p></div>')
    return "\n".join(out)


def type_rows():
    out = []
    for role, node in T.tokens("type"):
        s = T.style(role)
        weight = {400: "Regular", 500: "Medium", 700: "Bold"}.get(s["weight"], str(s["weight"]))
        spec = escape(SPECIMEN[role])
        sample = (f'<div class="dark"><span class="code"><span class="prompt">$</span>{spec[1:]}</span></div>' if role == "code"
                  else f'<p class="sample" style="font: var(--type-{role})">{spec}</p>')
        out.append(f'<div class="row">{sample}<div class="meta"><p class="body medium">{role}</p>'
                   f'<p class="tag">{s["family"]} {weight} · {s["size"]} / {s["line"]}</p>'
                   f'<p class="label use">{escape(node.get("$description", ""))}</p></div></div>')
    return "\n".join(out)


